CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password TEXT NOT NULL,
  provider VARCHAR(100) NOT NULL DEFAULT 'local',
  confirmed BOOLEAN NOT NULL DEFAULT TRUE,
  blocked BOOLEAN NOT NULL DEFAULT FALSE,
  image_id BIGINT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT users_username_length CHECK (char_length(username) >= 3),
  CONSTRAINT users_password_length CHECK (char_length(password) >= 6)
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS uploads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  url TEXT NOT NULL,
  mime VARCHAR(255) NOT NULL,
  size DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_image_id_fkey;
ALTER TABLE users ADD CONSTRAINT users_image_id_fkey FOREIGN KEY (image_id) REFERENCES uploads(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS thread_sets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT thread_sets_name_length CHECK (char_length(name) BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS threads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  is_fixed BOOLEAN NOT NULL DEFAULT FALSE,
  thread_set_id BIGINT REFERENCES thread_sets(id) ON DELETE SET NULL,
  author_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT threads_title_length CHECK (char_length(title) BETWEEN 1 AND 200)
);
CREATE INDEX IF NOT EXISTS threads_created_at_idx ON threads(created_at DESC);
CREATE INDEX IF NOT EXISTS threads_thread_set_id_idx ON threads(thread_set_id);
CREATE INDEX IF NOT EXISTS threads_author_id_idx ON threads(author_id);

CREATE TABLE IF NOT EXISTS responses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content TEXT NOT NULL,
  thread_id BIGINT REFERENCES threads(id) ON DELETE CASCADE,
  author_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  published_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT responses_content_not_empty CHECK (char_length(content) >= 1)
);
CREATE INDEX IF NOT EXISTS responses_thread_id_idx ON responses(thread_id);
CREATE INDEX IF NOT EXISTS responses_created_at_idx ON responses(created_at ASC);
